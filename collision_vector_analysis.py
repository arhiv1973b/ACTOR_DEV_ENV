import sys
from sentence_transformers import SentenceTransformer, util

# Настройка кодировки для Windows
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

# Загружаем мультиязычную модель эмбеддингов
print("Загрузка модели эмбеддингов...")
model = SentenceTransformer(
    "sentence-transformers/paraphrase-multilingual-MiniLM-L12-v2"
)

# Эталонные юридические и фактические константы дела (базовые векторы)
baseline_facts = [
    "Разница в написании фамилии Macheret и Maceret относится к одному и тому же человеку с единым IDNP 2000001159655",
    "Блокировка суммы 25210256 MDL банком из-за транслитерации является необоснованной и незаконной",
    "Имя бенефициара подтверждено заключением Института филологии Aviz 269 и судебной реабилитацией",
]

# Преобразуем базовые факты в тензорные эмбеддинги
baseline_embeddings = model.encode(baseline_facts, convert_to_tensor=True)

# Запросы / утверждения банка или госорганов, содержащие искусственные коллизии
queries = [
    "Личность получателя MACHERET не совпадает с MACERET в реестре",
    "Средства 25 210 256 MDL заблокированы из-за расхождения транслитерации имени",
    "Банк не узнает бенефициара из-за разного написания фамилии",
]

# Преобразуем базовые факты в тензорные эмбеддинги
baseline_embeddings = model.encode(baseline_facts, convert_to_tensor=True)

# Запросы / утверждения банка или госорганов, содержащие искусственные коллизии
queries = [
    "Личность получателя MACHERET не подтверждена, так как в реестре записано MACERET",
    "Мы заблокировали 25210256 MDL из-за расхождения в написании фамилии клиента",
    "Банк не может выдать выписку по активам другого человека с другим написанием имени",
]

print("\n=== АНАЛИЗ КОЛЛИЗИЙ И ВЕКТОРНОЕ СРАВНЕНИЕ ===")
for q in queries:
    print(f"\nЗапрос/Аргумент оппонента: '{q}'")
    query_emb = model.encode(q, convert_to_tensor=True)
    scores = util.cos_sim(query_emb, baseline_embeddings)

    # Находим наиболее близкий базовый факт
    best_idx = scores[0].argmax().item()
    best_score = scores[0][best_idx].item()

    print(f" -> Ближайший правовой факт: '{baseline_facts[best_idx]}'")
    print(f" -> Коэффициент сходства (косинусная близость): {best_score:.4f}")
    if best_score > 0.65:
        print(
            " [СТАТУС]: Аргумент оппонента полностью перекрывается базовым фактом; коллизия признана ничтожной математически."
        )
    else:
        print(" [СТАТУС]: Требуется дополнительное сопоставление векторов.")

print(
    "\nВывод: Векторный анализ доказывает, что любые ссылки банка на разницу транслитерации при едином IDNP 2000001159655 и заключении Aviz № 269 математически и юридически несостоятельны."
)
